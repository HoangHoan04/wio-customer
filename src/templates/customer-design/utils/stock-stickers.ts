function fluent(name: string): string {
  return `https://api.iconify.design/fluent-emoji/${name}.svg?height=128`;
}

function lucide(name: string): string {
  return `https://api.iconify.design/lucide/${name}.svg?height=128&color=%232D231F`;
}

function item(
  id: string,
  title: string,
  category: StockSticker["category"],
  keywords: string,
  set: StockSticker["set"],
  icon: string,
): StockSticker {
  return {
    id,
    title,
    category,
    keywords,
    set,
    icon,
    sourceUrl: set === "lucide" ? lucide(icon) : fluent(icon),
    url: `/stickers/${category}/${id}.png`,
    kind: category === "ornament" ? "ornament" : "sticker",
  };
}

