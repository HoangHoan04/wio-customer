export type StickerCategoryId =
  | "all"
  | "hearts"
  | "flowers"
  | "party"
  | "wedding"
  | "graduation"
  | "birthday"
  | "baby"
  | "nature"
  | "stars"
  | "ornament";

export type StickerKind = "sticker" | "ornament";

export interface StockSticker {
  id: string;
  title: string;
  category: Exclude<StickerCategoryId, "all">;
  keywords: string;
  url: string;
  sourceUrl: string;
  set: "fluent-emoji" | "lucide";
  icon: string;
  kind: StickerKind;
}

